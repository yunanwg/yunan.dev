#!/usr/bin/env python3
"""Draw Fig. 1 (the cover ride) from assets/tmb-profile.json (git-ignored).

Writes three things into the reference page, between markers:
- the SVG profile: x = share of distance, y = elevation;
- the reveal keyframes: the edge advances at the pace the route was walked,
  so a stop in time maps to how far along the route I was at that moment;
- the caption numbers.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
PAGE = ROOT / "site/index.html"
DATA = ROOT / "assets/tmb-profile.json"
W, H, TOP = 1200, 140, 46     # viewBox, and headroom above the highest point for labels
DURATION_S = 12               # the whole route, compressed
STOPS = 60                    # keyframe stops along the time axis


def require(*paths) -> None:
    """Generators need the git-ignored originals, which exist only on the author's machine."""
    missing = [str(p.relative_to(ROOT)) for p in paths if not p.exists()]
    if missing:
        raise SystemExit(f"missing {', '.join(missing)}: this generator runs where the originals live "
                         "(assets/ is git-ignored). The committed outputs in site/ are enough to build.")


def smooth(values, k=2):
    out = []
    for i in range(len(values)):
        win = values[max(0, i - k): i + k + 1]
        out.append(sum(win) / len(win))
    return out


def main() -> None:
    require(DATA)
    data = json.loads(DATA.read_text())
    full = data["profile"]  # [distance share, time share, elevation m]
    prof = full[::2] + ([full[-1]] if len(full) % 2 == 0 else [])  # drawing resolution, ~6 units apart
    ele = smooth([p[2] for p in prof], k=1)
    lo, hi = min(ele), max(ele)
    base_lo, base_hi = 900, max(2500, hi)
    y_of = lambda e: round(H - 2 - (e - base_lo) / (base_hi - base_lo) * (H - 2 - TOP), 1)
    pts = [(round(p[0] * W), y_of(e)) for p, e in zip(prof, ele)]

    # day separators and named high points, revealed with the ride
    names = {p["day"]: p["name"] for p in data["peaks"]}
    starts = data["day_starts"] + [1.0]
    marks = []
    for i in range(data["days"]):
        x0, x1 = starts[i] * W, starts[i + 1] * W
        if i:
            marks.append(f'<line class="day" x1="{x0:.0f}" x2="{x0:.0f}" y1="14" y2="{H}"/>')
        marks.append(f'<text class="dayn" x="{(x0 + x1) / 2:.0f}" y="11">{i + 1}</text>')
        seg = [p for p in full if starts[i] <= p[0] < starts[i + 1]]  # labels use full resolution
        top = max(seg, key=lambda p: p[2])
        if i + 1 in names:
            x = top[0] * W
            k = min(range(len(prof)), key=lambda n: abs(prof[n][0] - top[0]))
            y = pts[k][1]
            anchor = "end" if x > W - 60 else "middle"
            marks.append(f'<circle class="peak" cx="{x:.0f}" cy="{y}" r="2.2"/>'
                         f'<text class="peakl" x="{x:.0f}" y="{y - 15:.1f}" text-anchor="{anchor}">{names[i + 1]}</text>'
                         f'<text class="peakv" x="{x:.0f}" y="{y - 6:.1f}" text-anchor="{anchor}">{top[2]:,} m</text>')
    # One shape for ground and line: the closing edges run outside the viewBox, so only the profile's stroke shows.
    ride = f"M-10,{H + 10} L" + " L".join(f"{x},{y}" for x, y in pts) + f" L{W + 10},{H + 10}Z"

    # time share -> distance share, sampled at even time steps
    stops = []
    j = 0
    for i in range(STOPS + 1):
        t = i / STOPS
        while j < len(prof) - 1 and prof[j + 1][1] <= t:
            j += 1
        if j < len(prof) - 1 and prof[j + 1][1] > prof[j][1]:
            a, b = prof[j], prof[j + 1]
            d = a[0] + (b[0] - a[0]) * (t - a[1]) / (b[1] - a[1])
        else:
            d = prof[j][0]
        stops.append(f"{t * 100:.4g}% {{ clip-path: inset(0 {max(0, 100 - d * 100):.2f}% 0 0); }}")

    svg = (
        f'<svg viewBox="0 0 {W} {H}" preserveAspectRatio="xMidYMax slice" role="img" '
        f'aria-label="Elevation profile of the Tour du Mont Blanc, {data["garmin_distance_km"]:.0f} km over '
        f'{data["days"]} days, from {lo:.0f} to {hi:.0f} metres">\n'
        f'      <g class="ride-g">\n'
        f'      <path d="{ride}" fill="url(#dither-l)" stroke="currentColor" stroke-width="1.6" '
        f'stroke-linejoin="round" vector-effect="non-scaling-stroke"/>\n'
        f'      <g class="ride-marks" aria-hidden="true">{"".join(marks)}</g>\n'
        f'      </g>\n    </svg>'
    )
    css = (
        "/* fig1:start (generated by scripts/fig1.py) */\n"
        "/* The one load moment: the ride is revealed at the pace it was walked, line and ground\n"
        "   together, behind one moving edge. Base state is complete; the animation only reveals it. */\n"
        "@media screen and (prefers-reduced-motion: no-preference) {\n"
        f"  .cover .ride-g {{ animation: ride {DURATION_S}s linear both; }}\n"
        "  @keyframes ride {\n    " + "\n    ".join(stops) + "\n  }\n"
        "}\n/* fig1:end */"
    )
    caption = (
        f'<figcaption>Fig. 1. Tour du Mont Blanc, solo, June 2025: {data["garmin_distance_km"]:.0f} km, '
        f'+{data["garmin_ascent_m"]:,} m, {data["days"]} days on foot. Drawn at the pace I walked it.</figcaption>'
    )

    page = PAGE.read_text()
    page, n1 = re.subn(r'<svg viewBox="0 0 1200 \d+" preserveAspectRatio="xMidYMax slice".*?</svg>', svg, page, count=1, flags=re.S)
    page, n2 = re.subn(r'/\* fig1:start.*?/\* fig1:end \*/', css, page, count=1, flags=re.S)
    page, n3 = re.subn(r'<figcaption>Fig\. 1\..*?</figcaption>', caption, page, count=1, flags=re.S)
    assert (n1, n2, n3) == (1, 1, 1), (n1, n2, n3)
    PAGE.write_text(page)
    print(f"Fig. 1: {len(pts)} points, {lo:.0f}-{hi:.0f} m, {STOPS} stops over {DURATION_S} s")


if __name__ == "__main__":
    main()
